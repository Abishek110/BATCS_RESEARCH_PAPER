def validate_expected_coverage(
    all_df: pd.DataFrame,
) -> Dict[str, Any]:
    report: Dict[str, Any] = {"passed": True, "checks": []}

    def check(name: str, ok: bool, detail: str) -> None:
        report["checks"].append(
            {"name": name, "passed": bool(ok), "detail": detail}
        )
        if not ok:
            report["passed"] = False

    for experiment in ["E1", "E2", "E3", "E4"]:
        d = all_df[all_df["Experiment"] == experiment].copy()
        check(
            f"{experiment}_exists",
            not d.empty,
            f"rows={len(d)}",
        )

        if d.empty:
            continue

        seeds = sorted(d["Seed"].unique().tolist())
        if experiment == "E1":
            expected_seeds = EXPECTED_SEEDS
            check(
                "E1_five_seeds",
                set(seeds) == set(expected_seeds),
                f"observed={seeds}, expected={expected_seeds} (order-insensitive)",
            )
            alpha_values = sorted(d["Alpha"].unique().tolist())
            check(
                "E1_alpha",
                np.allclose(alpha_values, [0.5]),
                f"observed={alpha_values}",
            )
            budget_values = sorted(d["Budget_Ratio"].unique().tolist())
            check(
                "E1_budget",
                np.allclose(budget_values, [0.5]),
                f"observed={budget_values}",
            )

        elif experiment == "E2":
            expected_seeds = EXPECTED_SEEDS
            check(
                "E2_five_frozen_seeds",
                set(seeds) == set(expected_seeds),
                f"observed={seeds}, expected={expected_seeds} (order-insensitive)",
            )
            budget_values = sorted(d["Budget_Ratio"].unique().tolist())
            check(
                "E2_budget",
                np.allclose(budget_values, [0.5]),
                f"observed={budget_values}",
            )

        elif experiment == "E3":
            check(
                "E3_five_seeds",
                set(seeds) == set(EXPECTED_SEEDS),
                f"observed={seeds}, expected={EXPECTED_SEEDS} (order-insensitive)",
            )
            ratios = sorted(d["Budget_Ratio"].unique().tolist())
            check(
                "E3_four_budget_ratios",
                np.allclose(ratios, E3_BUDGET_RATIOS),
                f"observed={ratios}, expected={E3_BUDGET_RATIOS}",
            )

        elif experiment == "E4":
            check(
                "E4_five_seeds",
                set(seeds) == set(EXPECTED_SEEDS),
                f"observed={seeds}, expected={EXPECTED_SEEDS} (order-insensitive)",
            )
            alphas = sorted(d["Alpha"].unique().tolist())
            expected_alphas = sorted(E4_ALPHAS)
            check(
                "E4_three_alphas",
                np.allclose(alphas, expected_alphas),
                f"observed={alphas}, expected={expected_alphas} (order-insensitive)",
            )

    return report


