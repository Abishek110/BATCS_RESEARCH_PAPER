# FALSE-REJECTION ANALYSIS
# =============================================================================

def false_rejection_table(all_df: pd.DataFrame) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []

    for (experiment, alpha, budget_ratio, seed), g in all_df.groupby(
        ["Experiment", "Alpha", "Budget_Ratio", "Seed"],
        sort=True,
    ):
        rejected = ~g["Accepted"]
        positive_rejected = rejected & (g["Isolated_Utility_pp"] > 0.0)
        positive_all = g["Isolated_Utility_pp"] > 0.0

        rows.append(
            {
                "Experiment": experiment,
                "Alpha": float(alpha),
                "Budget_Ratio": float(budget_ratio),
                "Seed": int(seed),
                "Selected": int(len(g)),
                "Rejected": int(rejected.sum()),
                "Positive_Isolated_Utility_Total": int(positive_all.sum()),
                "Positive_Isolated_Utility_Rejected": int(positive_rejected.sum()),
                "False_Rejection_Rate_Among_Rejected": (
                    float(positive_rejected.sum() / rejected.sum())
                    if rejected.sum() > 0 else np.nan
                ),
                "Positive_Utility_Recall": (
                    float(
                        (positive_all & (~positive_rejected)).sum()
                        / positive_all.sum()
                    )
                    if positive_all.sum() > 0 else np.nan
                ),
            }
        )

    return pd.DataFrame(rows)


