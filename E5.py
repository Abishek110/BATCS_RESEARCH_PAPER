def load_manifest(candidates: Sequence[Path]) -> Optional[Dict[str, Any]]:
    for path in candidates:
        if path.is_file():
            try:
                with open(path, "r", encoding="utf-8") as fh:
                    return json.load(fh)
            except Exception as exc:
                raise RuntimeError(f"Could not parse manifest {path}: {exc}") from exc
    return None


