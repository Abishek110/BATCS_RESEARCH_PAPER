def finite_float(value: Any) -> bool:
    try:
        return math.isfinite(float(value))
    except (TypeError, ValueError):
        return False


def safe_float(value: Any) -> float:
    x = float(value)
    if not math.isfinite(x):
        raise ValueError(f"Expected finite float, got {value!r}")
    return x


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_json(path: Path, payload: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, allow_nan=False)
    os.replace(tmp, path)


def normalize_bool_series(series: pd.Series) -> pd.Series:
    if pd.api.types.is_bool_dtype(series):
        return series.astype(bool)

    mapping = {
        True: True,
        False: False,
        "True": True,
        "False": False,
        "true": True,
        "false": False,
        "1": True,
        "0": False,
        1: True,
        0: False,
    }
    mapped = series.map(mapping)
    if mapped.isna().any():
        bad = series[mapped.isna()].astype(str).unique().tolist()
        raise ValueError(f"Cannot normalize boolean column; bad values: {bad[:10]}")
    return mapped.astype(bool)


def mean_std(values: Sequence[float]) -> Tuple[float, float]:
    x = np.asarray(values, dtype=np.float64)
    x = x[np.isfinite(x)]
    if x.size == 0:
        return float("nan"), float("nan")
    mean = float(np.mean(x))
    std = float(np.std(x, ddof=1)) if x.size > 1 else 0.0
    return mean, std


def pearson_corr(x: np.ndarray, y: np.ndarray) -> float:
    if x.size < 2 or y.size < 2:
        return float("nan")
    x0 = x - x.mean()
    y0 = y - y.mean()
    denom = math.sqrt(float(np.sum(x0 * x0) * np.sum(y0 * y0)))
    if denom <= 0:
        return float("nan")
    return float(np.sum(x0 * y0) / denom)


def rank_average(values: np.ndarray) -> np.ndarray:
    """Average ranks, matching Spearman's tie handling."""
    order = np.argsort(values, kind="mergesort")
    sorted_vals = values[order]
    ranks = np.empty(values.size, dtype=np.float64)
    i = 0
    while i < values.size:
        j = i + 1
        while j < values.size and sorted_vals[j] == sorted_vals[i]:
            j += 1
        avg_rank = (i + 1 + j) / 2.0
        ranks[order[i:j]] = avg_rank
        i = j
    return ranks


def spearman_corr(x: np.ndarray, y: np.ndarray) -> float:
    if x.size < 2 or y.size < 2:
        return float("nan")
    return pearson_corr(rank_average(x), rank_average(y))


def regression_metrics(pred: pd.Series, actual: pd.Series) -> Dict[str, Any]:
    pair = pd.DataFrame({"pred": pred, "actual": actual}).replace(
        [np.inf, -np.inf], np.nan
    ).dropna()
    n = len(pair)

    if n == 0:
        return {
            "n": 0,
            "mae": np.nan,
            "rmse": np.nan,
            "bias": np.nan,
            "r2": np.nan,
            "spearman": np.nan,
        }

    p = pair["pred"].to_numpy(dtype=np.float64)
    y = pair["actual"].to_numpy(dtype=np.float64)
    err = p - y

    mae = float(np.mean(np.abs(err)))
    rmse = float(np.sqrt(np.mean(err ** 2)))
    bias = float(np.mean(err))

    sse = float(np.sum((y - p) ** 2))
    centered = float(np.sum((y - np.mean(y)) ** 2))
    r2 = float(1.0 - sse / centered) if centered > 0 else np.nan
    rho = spearman_corr(p, y)

    return {
        "n": int(n),
        "mae": mae,
        "rmse": rmse,
        "bias": bias,
        "r2": r2,
        "spearman": rho,
    }


def uncertainty_metrics(
    pred: pd.Series,
    actual: pd.Series,
    uncertainty: pd.Series,
) -> Dict[str, Any]:
    d = pd.DataFrame(
        {"pred": pred, "actual": actual, "unc": uncertainty}
    ).replace([np.inf, -np.inf], np.nan).dropna()

    d = d[d["unc"] >= 0].copy()
    if d.empty:
        return {
            "n_uncertainty": 0,
            "coverage_1sigma": np.nan,
            "coverage_2sigma": np.nan,
            "median_abs_error_over_uncertainty": np.nan,
        }

    abs_err = (d["pred"] - d["actual"]).abs().to_numpy(dtype=np.float64)
    unc = d["unc"].to_numpy(dtype=np.float64)

    one_sigma = float(np.mean(abs_err <= unc))
    two_sigma = float(np.mean(abs_err <= 2.0 * unc))

    safe_unc = np.maximum(unc, 1e-12)
    ratio = float(np.median(abs_err / safe_unc))

    return {
        "n_uncertainty": int(len(d)),
        "coverage_1sigma": one_sigma,
        "coverage_2sigma": two_sigma,
        "median_abs_error_over_uncertainty": ratio,
    }




def ranking_metrics(pred: pd.Series, actual: pd.Series) -> Dict[str, Any]:
    """Decision-oriented ranking diagnostics on observed labels only.

    These labels are available only for accepted clients by construction.
    Therefore this function never imputes rejected labels and never claims to
    evaluate pre-decision utility for rejected clients.
    """
    d = pd.DataFrame({"pred": pred, "actual": actual}).replace(
        [np.inf, -np.inf], np.nan
    ).dropna()
    if d.empty:
        return {
            "n": 0,
            "constant_mae": np.nan,
            "predictor_mae": np.nan,
            "relative_mae_improvement_pct": np.nan,
            "top1_actual_mean": np.nan,
            "top3_actual_mean": np.nan,
            "top5_actual_mean": np.nan,
            "top1_oracle_mean": np.nan,
            "top3_oracle_mean": np.nan,
            "top5_oracle_mean": np.nan,
            "top1_regret_pp": np.nan,
            "top3_regret_pp": np.nan,
            "top5_regret_pp": np.nan,
        }

    p = d["pred"].to_numpy(dtype=np.float64)
    y = d["actual"].to_numpy(dtype=np.float64)
    predictor_mae = float(np.mean(np.abs(p - y)))
    constant_mae = float(np.mean(np.abs(y - np.mean(y))))
    improvement = (
        100.0 * (constant_mae - predictor_mae) / constant_mae
        if constant_mae > 0 else np.nan
    )

    out: Dict[str, Any] = {
        "n": int(len(d)),
        "constant_mae": constant_mae,
        "predictor_mae": predictor_mae,
        "relative_mae_improvement_pct": improvement,
    }
    order = np.argsort(-p, kind="mergesort")
    oracle_order = np.argsort(-y, kind="mergesort")
    for k in (1, 3, 5):
        kk = min(k, len(d))
        pred_mean = float(np.mean(y[order[:kk]]))
        oracle_mean = float(np.mean(y[oracle_order[:kk]]))
        out[f"top{k}_actual_mean"] = pred_mean
        out[f"top{k}_oracle_mean"] = oracle_mean
        out[f"top{k}_regret_pp"] = oracle_mean - pred_mean
    return out


def uncertainty_rank_metrics(
    pred: pd.Series,
    actual: pd.Series,
    uncertainty: pd.Series,
) -> Dict[str, Any]:
    d = pd.DataFrame(
        {"pred": pred, "actual": actual, "unc": uncertainty}
    ).replace([np.inf, -np.inf], np.nan).dropna()
    d = d[d["unc"] >= 0].copy()
    if len(d) < 2:
        return {"n": int(len(d)), "error_uncertainty_spearman": np.nan}
    rho = spearman_corr(
        d["unc"].to_numpy(dtype=np.float64),
        np.abs(d["pred"].to_numpy(dtype=np.float64) - d["actual"].to_numpy(dtype=np.float64)),
    )
    return {"n": int(len(d)), "error_uncertainty_spearman": rho}


def decision_quality(df: pd.DataFrame) -> Dict[str, Any]:
    """Post-hoc decision diagnostics using the fully observed isolated utility.

    Isolated_Utility_pp is explicitly secondary. It is never substituted for
    the online aggregate-marginal target. These diagnostics ask whether the
    actual acceptance decision tends to retain higher isolated-utility clients
    than rejection, and how far the accepted set is from an isolated-utility
    top-k oracle of the same size.
    """
    g = df.copy()
    accepted = g["Accepted"].astype(bool)
    rejected = ~accepted
    a = g.loc[accepted, SECONDARY_TARGET].dropna().to_numpy(dtype=np.float64)
    r = g.loc[rejected, SECONDARY_TARGET].dropna().to_numpy(dtype=np.float64)
    all_u = g[SECONDARY_TARGET].dropna().to_numpy(dtype=np.float64)

    k = len(a)
    accepted_mean = float(np.mean(a)) if len(a) else np.nan
    rejected_mean = float(np.mean(r)) if len(r) else np.nan
    separation = accepted_mean - rejected_mean if len(a) and len(r) else np.nan
    oracle_mean = np.nan
    oracle_gap = np.nan
    random_expected = float(np.mean(all_u)) if len(all_u) else np.nan
    if k > 0 and len(all_u) >= k:
        oracle_mean = float(np.mean(np.sort(all_u)[-k:]))
        oracle_gap = oracle_mean - accepted_mean

    positive = g[SECONDARY_TARGET] > 0.0
    tp = int((accepted & positive).sum())
    fp = int((accepted & ~positive).sum())
    fn = int((rejected & positive).sum())
    precision = tp / (tp + fp) if (tp + fp) else np.nan
    recall = tp / (tp + fn) if (tp + fn) else np.nan
    f1 = (
        2.0 * precision * recall / (precision + recall)
        if np.isfinite(precision) and np.isfinite(recall) and (precision + recall) > 0
        else np.nan
    )

    return {
        "Selected": int(len(g)),
        "Accepted": int(accepted.sum()),
        "Rejected": int(rejected.sum()),
        "Accepted_Isolated_Mean_pp": accepted_mean,
        "Rejected_Isolated_Mean_pp": rejected_mean,
        "Accepted_minus_Rejected_Isolated_pp": separation,
        "Random_Expected_Isolated_Mean_pp": random_expected,
        "Oracle_TopK_Isolated_Mean_pp": oracle_mean,
        "Oracle_Gap_Isolated_pp": oracle_gap,
        "Positive_Isolated_Precision": precision,
        "Positive_Isolated_Recall": recall,
        "Positive_Isolated_F1": f1,
    }


def build_ranking_quality(all_df: pd.DataFrame) -> pd.DataFrame:
    """Evaluate ranking quality at the round level, then average by job.

    The original ranking diagnostic pooled all accepted labels across an entire
    seed and then computed Top-1/3/5.  That is not the BATCS decision unit: the
    Stage-2 decision is made separately in every round.  This implementation
    therefore computes the ranking metrics independently within each round and
    then macro-averages those round-level metrics within each job.  Rejected
    clients are not assigned fabricated primary targets.
    """
    rows = []
    d = all_df[all_df[PRIMARY_TARGET].notna()].copy()
    job_cols = ["Experiment", "Alpha", "Budget_Ratio", "Seed"]
    for key, job in d.groupby(job_cols, sort=True):
        experiment, alpha, budget_ratio, seed = key
        round_metrics_list = []
        for _, rg in job.groupby("Round", sort=True):
            m = ranking_metrics(rg[PREDICTION], rg[PRIMARY_TARGET])
            if m["n"] >= 2:
                round_metrics_list.append(m)

        row = {
            "Experiment": experiment,
            "Alpha": float(alpha),
            "Budget_Ratio": float(budget_ratio),
            "Seed": int(seed),
            "Ranking_Rounds_Evaluated": int(len(round_metrics_list)),
        }
        metric_names = [
            "n", "constant_mae", "predictor_mae",
            "relative_mae_improvement_pct",
            "top1_actual_mean", "top3_actual_mean", "top5_actual_mean",
            "top1_oracle_mean", "top3_oracle_mean", "top5_oracle_mean",
            "top1_regret_pp", "top3_regret_pp", "top5_regret_pp",
        ]
        for name in metric_names:
            vals = np.asarray(
                [m[name] for m in round_metrics_list], dtype=np.float64
            )
            row[name] = float(np.nanmean(vals)) if vals.size else np.nan

        # Use the stable report-facing names expected elsewhere in E5.
        row.update({
            "Predictor_vs_Constant_MAE_Improvement_pct": row["relative_mae_improvement_pct"],
            "Top1_Actual_Utility_pp": row["top1_actual_mean"],
            "Top3_Actual_Utility_pp": row["top3_actual_mean"],
            "Top5_Actual_Utility_pp": row["top5_actual_mean"],
            "Top1_Oracle_Utility_pp": row["top1_oracle_mean"],
            "Top3_Oracle_Utility_pp": row["top3_oracle_mean"],
            "Top5_Oracle_Utility_pp": row["top5_oracle_mean"],
            "Top1_Regret_pp": row["top1_regret_pp"],
            "Top3_Regret_pp": row["top3_regret_pp"],
            "Top5_Regret_pp": row["top5_regret_pp"],
        })
        rows.append(row)

    return pd.DataFrame(rows)


def build_decision_quality(all_df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (experiment, alpha, budget_ratio, seed), g in all_df.groupby(
        ["Experiment", "Alpha", "Budget_Ratio", "Seed"], sort=True
    ):
        rows.append({
            "Experiment": experiment,
            "Alpha": float(alpha),
            "Budget_Ratio": float(budget_ratio),
            "Seed": int(seed),
            **decision_quality(g),
        })
    return pd.DataFrame(rows)


def build_uncertainty_calibration(all_df: pd.DataFrame) -> pd.DataFrame:
    """Decile-wise error/coverage; no recalibration is performed."""
    rows = []
    d = all_df[all_df[PRIMARY_TARGET].notna()].copy()
    for (experiment, alpha, budget_ratio, seed), g in d.groupby(
        ["Experiment", "Alpha", "Budget_Ratio", "Seed"], sort=True
    ):
        x = g[[PREDICTION, PRIMARY_TARGET, UNCERTAINTY]].replace(
            [np.inf, -np.inf], np.nan
        ).dropna()
        x = x[x[UNCERTAINTY] >= 0].copy()
        if len(x) < 10:
            continue
        x["Abs_Error_pp"] = (x[PREDICTION] - x[PRIMARY_TARGET]).abs()
        x["Unc_Decile"] = pd.qcut(
            x[UNCERTAINTY], q=10, labels=False, duplicates="drop"
        ) + 1
        for decile, z in x.groupby("Unc_Decile", sort=True):
            rows.append({
                "Experiment": experiment,
                "Alpha": float(alpha),
                "Budget_Ratio": float(budget_ratio),
                "Seed": int(seed),
                "Uncertainty_Decile": int(decile),
                "N": int(len(z)),
                "Mean_Uncertainty_pp": float(z[UNCERTAINTY].mean()),
                "Mean_Absolute_Error_pp": float(z["Abs_Error_pp"].mean()),
                "Median_Absolute_Error_pp": float(z["Abs_Error_pp"].median()),
                "Coverage_1sigma": float((z["Abs_Error_pp"] <= z[UNCERTAINTY]).mean()),
                "Coverage_2sigma": float((z["Abs_Error_pp"] <= 2.0 * z[UNCERTAINTY]).mean()),
            })
    return pd.DataFrame(rows)

