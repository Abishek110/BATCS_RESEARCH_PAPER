def job_rows(df: pd.DataFrame) -> Iterable[Tuple[str, pd.DataFrame]]:
    group_cols = ["Experiment", "Seed", "Alpha", "Budget_Ratio"]

    for key, group in df.groupby(group_cols, dropna=False, sort=True):
        name = (
            f"{key[0]}|seed={int(key[1])}|"
            f"alpha={float(key[2]):g}|budget={float(key[3]):g}"
        )
        yield name, group.copy()


def compute_job_metrics(df: pd.DataFrame) -> Dict[str, Any]:
    experiment = str(df["Experiment"].iloc[0])
    seed = int(df["Seed"].iloc[0])
    alpha = float(df["Alpha"].iloc[0])
    budget_ratio = float(df["Budget_Ratio"].iloc[0])

    primary = regression_metrics(df[PREDICTION], df[PRIMARY_TARGET])
    secondary = regression_metrics(df[PREDICTION], df[SECONDARY_TARGET])
    unc_primary = uncertainty_metrics(
        df[PREDICTION],
        df[PRIMARY_TARGET],
        df[UNCERTAINTY],
    )
    unc_secondary = uncertainty_metrics(
        df[PREDICTION],
        df[SECONDARY_TARGET],
        df[UNCERTAINTY],
    )
    rank = ranking_metrics(df[PREDICTION], df[PRIMARY_TARGET])
    unc_rank = uncertainty_rank_metrics(
        df[PREDICTION], df[PRIMARY_TARGET], df[UNCERTAINTY]
    )
    decision = decision_quality(df)

    rejected = ~df["Accepted"]
    false_rejections = int(
        (rejected & (df["Isolated_Utility_pp"] > 0.0)).sum()
    )
    rejected_count = int(rejected.sum())
    accepted_count = int(df["Accepted"].sum())

    observed_target_count = int(df[PRIMARY_TARGET].notna().sum())
    total_rows = int(len(df))

    return {
        "Experiment": experiment,
        "Seed": seed,
        "Alpha": alpha,
        "Budget_Ratio": budget_ratio,

        "Total_Selected_Records": total_rows,
        "Accepted_Records": accepted_count,
        "Rejected_Records": rejected_count,
        "Observed_Primary_Target_Records": observed_target_count,
        "Observed_Primary_Target_Fraction": (
            observed_target_count / total_rows if total_rows else np.nan
        ),

        "Primary_n": primary["n"],
        "Primary_MAE_pp": primary["mae"],
        "Primary_RMSE_pp": primary["rmse"],
        "Primary_Bias_pp": primary["bias"],
        "Primary_R2": primary["r2"],
        "Primary_Spearman": primary["spearman"],
        "Constant_Mean_MAE_pp": rank["constant_mae"],
        "Predictor_vs_Constant_MAE_Improvement_pct": rank["relative_mae_improvement_pct"],
        "Top1_Actual_Utility_pp": rank["top1_actual_mean"],
        "Top3_Actual_Utility_pp": rank["top3_actual_mean"],
        "Top5_Actual_Utility_pp": rank["top5_actual_mean"],
        "Top1_Oracle_Utility_pp": rank["top1_oracle_mean"],
        "Top3_Oracle_Utility_pp": rank["top3_oracle_mean"],
        "Top5_Oracle_Utility_pp": rank["top5_oracle_mean"],
        "Top1_Regret_pp": rank["top1_regret_pp"],
        "Top3_Regret_pp": rank["top3_regret_pp"],
        "Top5_Regret_pp": rank["top5_regret_pp"],
        "Uncertainty_Error_Spearman": unc_rank["error_uncertainty_spearman"],

        "Isolated_n": secondary["n"],
        "Isolated_MAE_pp": secondary["mae"],
        "Isolated_RMSE_pp": secondary["rmse"],
        "Isolated_Bias_pp": secondary["bias"],
        "Isolated_R2": secondary["r2"],
        "Isolated_Spearman": secondary["spearman"],

        "Primary_Coverage_1sigma": unc_primary["coverage_1sigma"],
        "Primary_Coverage_2sigma": unc_primary["coverage_2sigma"],
        "Primary_Median_AbsError_over_Uncertainty": (
            unc_primary["median_abs_error_over_uncertainty"]
        ),

        "Isolated_Coverage_1sigma": unc_secondary["coverage_1sigma"],
        "Isolated_Coverage_2sigma": unc_secondary["coverage_2sigma"],
        "Isolated_Median_AbsError_over_Uncertainty": (
            unc_secondary["median_abs_error_over_uncertainty"]
        ),

        "Accepted_Isolated_Mean_pp": decision["Accepted_Isolated_Mean_pp"],
        "Rejected_Isolated_Mean_pp": decision["Rejected_Isolated_Mean_pp"],
        "Accepted_minus_Rejected_Isolated_pp": decision["Accepted_minus_Rejected_Isolated_pp"],
        "Random_Expected_Isolated_Mean_pp": decision["Random_Expected_Isolated_Mean_pp"],
        "Oracle_TopK_Isolated_Mean_pp": decision["Oracle_TopK_Isolated_Mean_pp"],
        "Oracle_Gap_Isolated_pp": decision["Oracle_Gap_Isolated_pp"],
        "Positive_Isolated_Precision": decision["Positive_Isolated_Precision"],
        "Positive_Isolated_Recall": decision["Positive_Isolated_Recall"],
        "Positive_Isolated_F1": decision["Positive_Isolated_F1"],

        "False_Rejections": false_rejections,
        "False_Rejection_Rate_Among_Rejected": (
            false_rejections / rejected_count
            if rejected_count > 0 else np.nan
        ),
        "Accepted_Fraction": (
            accepted_count / total_rows if total_rows else np.nan
        ),
    }


def build_job_metrics(all_df: pd.DataFrame) -> pd.DataFrame:
    records = [
        compute_job_metrics(group)
        for _, group in job_rows(all_df)
    ]
    out = pd.DataFrame(records)
    if out.empty:
        raise RuntimeError("No job-level metric records were created.")
    return out.sort_values(
        ["Experiment", "Alpha", "Budget_Ratio", "Seed"]
    ).reset_index(drop=True)


