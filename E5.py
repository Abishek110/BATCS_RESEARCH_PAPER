def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="BATCS E5 — Preview Predictor Evaluation"
    )
    parser.add_argument(
        "--root",
        type=str,
        default=str(DEFAULT_ROOT),
        help="Path to batcs_results_final",
    )
    parser.add_argument(
        "--out",
        type=str,
        default=str(DEFAULT_OUTPUT_DIR),
        help="Output directory for E5 reports",
    )
    parser.add_argument(
        "--no-plots",
        action="store_true",
        help="Skip plot generation",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        return run_e5(
            root=Path(args.root).expanduser().resolve(),
            output_dir=Path(args.out).expanduser().resolve(),
            make_plot_files=not args.no_plots,
        )
    except Exception as exc:
        print("\nE5 FAILED:", exc, file=sys.stderr)
        traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
