"""
BATCS — E5: PREVIEW PREDICTOR EVALUATION
=========================================

Purpose
-------
E5 is a READ-ONLY, post-hoc evaluation of the BATCS preview predictor using
the predictor records already generated by the frozen E1/E2/E3/E4 pipelines.

E5 does NOT:
    - retrain federated models,
    - rerun any FL rounds,
    - alter E1/E2/E3/E4 artifacts,
    - fit a replacement predictor,
    - use final test accuracy as a predictor target,
    - use future/current-round targets to recompute predictions.

The predictor predictions being evaluated were produced online during the
original FL experiments. The relevant target fields were observed only after
the Stage-2 decision and aggregation. Therefore this script evaluates the
stored predictions as PRE-DECISION predictions against POST-DECISION labels.

Frozen BATCS protocol assumptions
---------------------------------
    CIFAR-10
    50 clients
    exactly 10 clients selected before local training
    50 maximum rounds
    1 local epoch
    batch size 64
    learning rate 0.01
    momentum 0.9
    alpha = 0.5 for E1/E2
    budget ratio = 0.50 for E1/E2/E4
    E3 ratios = [0.25, 0.50, 0.75, 1.00]
    E4 alphas = [1.0, 0.5, 0.1]
    frozen E1 SHA256 =
    40249a6d3407865692eca22841a7940445642c9661322ab3cbd3f4232a578410

Predictor record schema
-----------------------
Expected BATCS predictor records include:
    Seed
    Round
    Client
    Predicted_Utility_pp
    Uncertainty_pp
    Risk_Utility_pp
    Utility_per_MB
    Combined_Score
    Accepted
    Observed_Marginal_Utility_pp
    Isolated_Utility_pp
    False_Rejection

Primary supervised target
-------------------------
    Observed_Marginal_Utility_pp

This is the same aggregate-marginal validation utility used by the online
predictor supervision in the frozen E1 implementation. The field is only
observed for accepted clients in the stored records, so E5 reports this
accepted-only metric explicitly rather than silently treating missing values
as zero.

Secondary diagnostic target
---------------------------
    Isolated_Utility_pp

This target exists for every selected client and is useful for evaluating
whether preview predictions align with the direction of a client's isolated
validation effect. It is a diagnostic target, NOT the online training target.

Metrics
-------
For each experiment / condition / seed:
    MAE
    RMSE
    bias = mean(predicted - actual)
    R^2
    Spearman rank correlation

Uncertainty diagnostics:
    empirical 1-sigma coverage
    empirical 2-sigma coverage
    median absolute error / uncertainty

Decision diagnostics:
    false-rejection rate among rejected clients with positive isolated utility
    positive-utility precision / recall / F1
    accepted-vs-rejected isolated-utility separation
    oracle top-k gap on the fully observed isolated-utility diagnostic

Ranking diagnostics:
    constant-mean MAE baseline and relative improvement
    top-k observed marginal utility among accepted clients
    oracle top-k regret among accepted labeled clients

Uncertainty diagnostics:
    empirical 1-sigma / 2-sigma coverage
    median absolute error / uncertainty
    rank correlation between uncertainty and absolute error
    absolute error and coverage by uncertainty decile

Aggregation
-----------
E5 reports both:
    1) per-job metrics (one metric record per experiment-condition-seed)
    2) macro mean ± sample SD across jobs
    3) micro pooled metrics across all valid rows

This avoids allowing E3/E4 to dominate a macro result merely because they
contain more predictor rows.

Source integrity
----------------
E5 expects:
    E1: batcs_results_final/E1_BATCS_predictor.csv
    E2: batcs_results_final/E2_stage2_novelty_isolation/E2_BATCS_predictor.csv
    E3: batcs_results_final/E3_budget_sensitivity/E3_BATCS_predictor.csv
    E4: batcs_results_final/E4_noniid_sensitivity/E4_BATCS_predictor.csv

E5 validates:
    - frozen E1 SHA recorded by experiment manifests where available,
    - expected experiment methods / seeds / alphas / budget ratios,
    - no duplicate observation key within a source,
    - numeric finiteness of required predictor/target fields,
    - no accidental use of final test accuracy as a predictor target,
    - causal role of Observed_Marginal_Utility_pp as a POST-decision label.

No source file is modified by this script.

Output
------
    batcs_results_final/E5_preview_predictor_evaluation/
        E5_all_predictor_records.csv
        E5_job_metrics.csv
        E5_summary.csv
        E5_primary_main.csv
        E5_by_alpha.csv
        E5_by_budget.csv
        E5_false_rejection.csv
        E5_round_metrics.csv
        E5_manifest.json
        plots/*.png

This is a deterministic analysis script. It contains no PyTorch/TorchVision
imports and therefore does not invoke MPS or GPU training.
"""

