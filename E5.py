def validate_manifest(
    experiment: str,
    manifest: Optional[Dict[str, Any]],
) -> List[str]:
    problems: List[str] = []
    if manifest is None:
        # E5 can still validate the CSV directly. Missing manifest is recorded,
        # but is not silently interpreted as a valid manifest.
        return ["source_manifest_missing"]

    if experiment in {"E2", "E3", "E4"}:
        observed_sha = manifest.get("e1_source_sha256")
        if observed_sha != EXPECTED_E1_SHA256:
            problems.append(
                f"E1 SHA mismatch in {experiment} manifest: "
                f"{observed_sha!r} != expected {EXPECTED_E1_SHA256!r}"
            )

    if experiment == "E3":
        if set(manifest.get("e3_seeds", [])) != set(EXPECTED_SEEDS):
            problems.append("E3 manifest seed set mismatch")
        if set(float(x) for x in manifest.get("e3_budget_ratios", [])) != set(E3_BUDGET_RATIOS):
            problems.append("E3 manifest budget-ratio set mismatch")
        if manifest.get("all_jobs_valid") is not True:
            problems.append("E3 manifest does not report all_jobs_valid=true")

    if experiment == "E4":
        if set(manifest.get("e4_seeds", [])) != set(EXPECTED_SEEDS):
            problems.append("E4 manifest seed set mismatch")
        if set(float(x) for x in manifest.get("e4_alphas", [])) != set(E4_ALPHAS):
            problems.append("E4 manifest alpha set mismatch")
        if manifest.get("all_jobs_valid") is not True:
            problems.append("E4 manifest does not report all_jobs_valid=true")

    return problems


def load_condition_from_job_artifacts(spec: Dict[str, Any]) -> pd.DataFrame:
    """Rebuild missing E3/E4 predictor condition metadata from job JSONs.

    The frozen E3/E4 launchers add budget/alpha identifiers to summaries and
    round records, but the copied predictor_records themselves inherit the E1
    schema.  Therefore the aggregate predictor CSV can legitimately lack the
    condition column.  This helper reads the already-produced BATCS job JSONs
    and attaches the condition that is explicitly stored at the job level.
    No FL execution or re-fitting occurs here.
    """
    experiment = spec["experiment"]
    result_dir = Path(spec["path"]).parent
    job_dir = result_dir / "jobs"
    if not job_dir.is_dir():
        raise RuntimeError(
            f"{experiment}: predictor CSV lacks its condition column and the "
            f"expected job artifact directory is missing: {job_dir}"
        )

    records: List[Dict[str, Any]] = []
    condition_col = "Budget_Ratio" if experiment == "E3" else "Alpha"
    expected_seeds = set(spec["expected_seeds"])

    for job_path in sorted(job_dir.glob("*.json")):
        try:
            with open(job_path, "r", encoding="utf-8") as fh:
                payload = json.load(fh)
        except Exception as exc:
            raise RuntimeError(f"{experiment}: could not parse job artifact {job_path}: {exc}") from exc

        if payload.get("method") != "BATCS":
            continue
        if payload.get("e1_source_sha256") not in {None, EXPECTED_E1_SHA256}:
            raise RuntimeError(
                f"{experiment}: job {job_path.name} has unexpected E1 source SHA "
                f"{payload.get('e1_source_sha256')!r}"
            )
        if payload.get("invariants_passed") is not True:
            raise RuntimeError(
                f"{experiment}: job {job_path.name} does not report invariants_passed=true"
            )

        try:
            seed = int(payload["seed"])
        except Exception as exc:
            raise RuntimeError(f"{experiment}: invalid seed in {job_path.name}") from exc
        if seed not in expected_seeds:
            raise RuntimeError(
                f"{experiment}: unexpected BATCS seed {seed} in {job_path.name}"
            )

        if experiment == "E3":
            if "budget_ratio" not in payload:
                raise RuntimeError(f"E3: job {job_path.name} lacks budget_ratio")
            condition_value = float(payload["budget_ratio"])
            if not any(np.isclose(condition_value, x, rtol=0.0, atol=1e-12) for x in E3_BUDGET_RATIOS):
                raise RuntimeError(
                    f"E3: job {job_path.name} has unsupported Budget_Ratio={condition_value}"
                )
        else:
            if "alpha" not in payload:
                raise RuntimeError(f"E4: job {job_path.name} lacks alpha")
            condition_value = float(payload["alpha"])
            if not any(np.isclose(condition_value, x, rtol=0.0, atol=1e-12) for x in E4_ALPHAS):
                raise RuntimeError(
                    f"E4: job {job_path.name} has unsupported Alpha={condition_value}"
                )
            budget_value = float(payload.get("budget_ratio", E4_BUDGET_RATIO))
            if not np.isclose(budget_value, E4_BUDGET_RATIO, rtol=0.0, atol=1e-12):
                raise RuntimeError(
                    f"E4: job {job_path.name} has unexpected budget_ratio={budget_value}"
                )

        predictor = payload.get("predictor_records", [])
        if not isinstance(predictor, list):
            raise RuntimeError(f"{experiment}: predictor_records in {job_path.name} is not a list")
        for raw in predictor:
            row = dict(raw)
            row[condition_col] = condition_value
            records.append(row)

    if not records:
        raise RuntimeError(
            f"{experiment}: no BATCS predictor_records were found in {job_dir}"
        )

    out = pd.DataFrame(records)
    return out


def load_and_validate_source(spec: Dict[str, Any]) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    experiment = spec["experiment"]
    path: Path = spec["path"]

    if not path.is_file():
        raise FileNotFoundError(
            f"{experiment} predictor source not found:\n  {path}\n"
            "Place E5.py beside batcs_results_final/."
        )

    manifest = load_manifest(spec["manifest_candidates"])
    manifest_problems = validate_manifest(experiment, manifest)
    fatal_manifest_problems = [
        p for p in manifest_problems if p != "source_manifest_missing"
    ]
    if fatal_manifest_problems:
        raise RuntimeError(
            f"{experiment} source manifest validation failed: "
            + "; ".join(fatal_manifest_problems)
        )

    df = pd.read_csv(path)

    # E3/E4 job JSONs are the authoritative predictor source because the
    # aggregate CSVs were produced by older launchers that did not reliably
    # propagate experiment-condition metadata.  Always rebuild E3/E4 predictor
    # provenance from the immutable job artifacts, and validate the aggregate
    # CSV against those records when possible.  This prevents a stale or
    # mis-labeled aggregate CSV from changing the scientific interpretation.
    if experiment in {"E3", "E4"}:
        condition_col = "Budget_Ratio" if experiment == "E3" else "Alpha"
        job_df = load_condition_from_job_artifacts(spec)

        if len(job_df) != len(df):
            raise RuntimeError(
                f"{experiment}: predictor CSV rows ({len(df)}) do not match "
                f"job-artifact predictor rows ({len(job_df)})"
            )

        # Compare the stable predictor fields. Condition metadata is validated
        # separately below; predictor values themselves must match the immutable
        # per-job records regardless of CSV row ordering.
        compare_cols = [
            "Seed", "Round", "Client",
            "Predicted_Utility_pp", "Uncertainty_pp",
            "Risk_Utility_pp", "Utility_per_MB", "Combined_Score",
            "Accepted", "Observed_Marginal_Utility_pp",
            "Isolated_Utility_pp", "False_Rejection",
        ]
        csv_cmp = df[compare_cols].copy()
        job_cmp = job_df[compare_cols].copy()
        for col in compare_cols:
            if col in {"Accepted", "False_Rejection"}:
                csv_cmp[col] = normalize_bool_series(csv_cmp[col])
                job_cmp[col] = normalize_bool_series(job_cmp[col])
            else:
                csv_cmp[col] = pd.to_numeric(csv_cmp[col], errors="coerce")
                job_cmp[col] = pd.to_numeric(job_cmp[col], errors="coerce")

        sort_cols = compare_cols
        csv_cmp = csv_cmp.sort_values(sort_cols, kind="mergesort", na_position="first").reset_index(drop=True)
        job_cmp = job_cmp.sort_values(sort_cols, kind="mergesort", na_position="first").reset_index(drop=True)
        try:
            pd.testing.assert_frame_equal(
                csv_cmp, job_cmp, check_dtype=False, check_exact=False,
                rtol=1e-12, atol=1e-12
            )
        except AssertionError as exc:
            raise RuntimeError(
                f"{experiment}: predictor CSV content does not match the "
                f"immutable job predictor records. Details: {exc}"
            ) from exc

        # If the CSV contains the condition column, verify that it too agrees
        # with the job-level provenance before replacing the CSV with canonical
        # job-derived data.
        if condition_col in df.columns:
            csv_condition = pd.to_numeric(df[condition_col], errors="coerce")
            job_condition = pd.to_numeric(job_df[condition_col], errors="coerce")
            csv_key = df[["Seed", "Round", "Client"]].copy()
            csv_key[condition_col] = csv_condition
            job_key = job_df[["Seed", "Round", "Client"]].copy()
            job_key[condition_col] = job_condition
            csv_key = csv_key.sort_values([condition_col, "Seed", "Round", "Client"]).reset_index(drop=True)
            job_key = job_key.sort_values([condition_col, "Seed", "Round", "Client"]).reset_index(drop=True)
            try:
                pd.testing.assert_frame_equal(
                    csv_key, job_key, check_dtype=False, check_exact=False,
                    rtol=0.0, atol=1e-12
                )
            except AssertionError as exc:
                raise RuntimeError(
                    f"{experiment}: aggregate {condition_col} metadata does not "
                    f"match immutable job provenance. Details: {exc}"
                ) from exc

        # Canonical E3/E4 dataframe used for every downstream metric.
        df = job_df

    missing = sorted(REQUIRED_COLUMNS - set(df.columns))
    if missing:
        raise RuntimeError(
            f"{experiment} predictor file is missing required columns: {missing}"
        )

    # Normalize provenance fields from the source itself.
    for col in ("Seed", "Round", "Client"):
        df[col] = pd.to_numeric(df[col], errors="coerce")
        if df[col].isna().any():
            raise RuntimeError(f"{experiment}: non-numeric values in {col}")
        df[col] = df[col].astype(int)

    for col in (
        "Predicted_Utility_pp",
        "Uncertainty_pp",
        "Risk_Utility_pp",
        "Utility_per_MB",
        "Combined_Score",
        "Observed_Marginal_Utility_pp",
        "Isolated_Utility_pp",
    ):
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df["Accepted"] = normalize_bool_series(df["Accepted"])
    df["False_Rejection"] = normalize_bool_series(df["False_Rejection"])

    # The source is BATCS predictor data by construction.
    df["Experiment"] = experiment

    if "Method" not in df.columns:
        df["Method"] = "BATCS"
    if "Method" in df.columns:
        bad_method = ~df["Method"].isin(spec["expected_methods"])
        if bad_method.any():
            raise RuntimeError(
                f"{experiment}: unexpected Method values: "
                f"{sorted(df.loc[bad_method, 'Method'].dropna().unique().tolist())}"
            )
    else:
        df["Method"] = "BATCS"

    # Add condition provenance from the source file.
    if experiment in {"E1", "E2"}:
        df["Alpha"] = spec["expected_alpha"]
        df["Budget_Ratio"] = spec["expected_budget_ratio"]
    elif experiment == "E3":
        if "Budget_Ratio" in df.columns:
            df["Budget_Ratio"] = pd.to_numeric(df["Budget_Ratio"], errors="coerce")
        else:
            raise RuntimeError("E3 predictor file must contain Budget_Ratio")
        df["Alpha"] = E1_ALPHA
    elif experiment == "E4":
        if "Alpha" in df.columns:
            df["Alpha"] = pd.to_numeric(df["Alpha"], errors="coerce")
        else:
            raise RuntimeError("E4 predictor file must contain Alpha")
        df["Budget_Ratio"] = E4_BUDGET_RATIO

    # Strict finite checks for prediction-side variables.
    for col in (
        "Predicted_Utility_pp",
        "Uncertainty_pp",
        "Risk_Utility_pp",
        "Utility_per_MB",
        "Combined_Score",
        "Isolated_Utility_pp",
    ):
        if not np.isfinite(df[col].to_numpy(dtype=np.float64)).all():
            raise RuntimeError(f"{experiment}: non-finite values in {col}")

    if (df["Uncertainty_pp"] < 0).any():
        raise RuntimeError(f"{experiment}: negative uncertainty values detected")

    if (df["Round"] < 1).any() or (df["Round"] > 50).any():
        raise RuntimeError(f"{experiment}: Round outside [1,50]")

    if (df["Client"] < 0).any() or (df["Client"] >= 50).any():
        raise RuntimeError(f"{experiment}: Client outside [0,49]")

    if not set(df["Seed"].tolist()).issubset(spec["expected_seeds"]):
        raise RuntimeError(
            f"{experiment}: unexpected seeds: "
            f"{sorted(set(df['Seed']) - spec['expected_seeds'])}"
        )

    # Duplicate key check. Each selected-client record must occur once.
    key_cols = ["Seed", "Round", "Client"]
    if experiment == "E3":
        key_cols = ["Budget_Ratio"] + key_cols
    elif experiment == "E4":
        key_cols = ["Alpha"] + key_cols

    dup = df.duplicated(subset=key_cols, keep=False)
    if dup.any():
        sample = df.loc[dup, key_cols].head(10).to_dict("records")
        raise RuntimeError(f"{experiment}: duplicate predictor records: {sample}")

    # Every round should have exactly 10 selected clients in BATCS predictor logs.
    # E3 contains four budget operating points and E4 contains three alpha
    # operating points, so the experimental condition MUST be part of the
    # grouping key. Otherwise the same Seed/Round records from different
    # conditions are pooled and a valid 10-client round can incorrectly appear
    # to contain >10 clients.
    count_group_cols = ["Seed", "Round"]
    if experiment == "E3":
        count_group_cols = ["Budget_Ratio", "Seed", "Round"]
    elif experiment == "E4":
        count_group_cols = ["Alpha", "Seed", "Round"]

    counts = (
        df.groupby(count_group_cols, dropna=False)["Client"]
        .nunique()
        .reset_index(name="n_clients")
    )
    if not counts.empty and not (counts["n_clients"] == 10).all():
        bad = counts[counts["n_clients"] != 10].head(10).to_dict("records")
        raise RuntimeError(
            f"{experiment}: some round logs do not contain exactly 10 clients: {bad}"
        )

    # Accepted flags must be boolean and isolated target must exist for all rows.
    if df["Isolated_Utility_pp"].isna().any():
        raise RuntimeError(
            f"{experiment}: Isolated_Utility_pp must exist for every predictor row"
        )

    # The stored False_Rejection flag must match its documented definition.
    expected_false_rejection = (
        (~df["Accepted"]) & (df["Isolated_Utility_pp"] > 0.0)
    )
    if not expected_false_rejection.equals(df["False_Rejection"]):
        mismatches = df.loc[
            expected_false_rejection != df["False_Rejection"],
            ["Seed", "Round", "Client", "Accepted",
             "Isolated_Utility_pp", "False_Rejection"]
        ].head(10)
        raise RuntimeError(
            f"{experiment}: False_Rejection field is inconsistent with "
            f"its documented definition:\n{mismatches}"
        )

    meta = {
        "experiment": experiment,
        "path": str(path),
        "sha256": sha256_file(path),
        "row_count": int(len(df)),
        "manifest_present": manifest is not None,
        "manifest_validation": manifest_problems,
        "source_e1_sha256": (
            manifest.get("e1_source_sha256") if manifest else None
        ),
    }

    return df, meta


